from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor


BLUE = RGBColor(0x00, 0x70, 0xC0)


def font(run, size=12, bold=False, italic=False, color=None):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color


def h1(doc, text):
    p = doc.add_heading(level=1)
    run = p.add_run(text)
    font(run, 14, bold=True, color=BLUE)


def h2(doc, text):
    p = doc.add_heading(level=2)
    run = p.add_run(text)
    font(run, 13, bold=True)


def para(doc, text, bold=False, italic=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    font(run, 12, bold=bold, italic=italic)
    p.paragraph_format.first_line_indent = Cm(1.0)
    p.paragraph_format.space_after = Pt(4)


def bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.clear()
    run = p.add_run(text)
    font(run, 12)


def cell(c, text, bold=False):
    c.text = ""
    run = c.paragraphs[0].add_run(text)
    font(run, 9, bold=bold)


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    for i, h in enumerate(headers):
        cell(t.rows[0].cells[i], h, bold=True)
    for r_i, row in enumerate(rows):
        for c_i, v in enumerate(row):
            cell(t.rows[r_i + 1].cells[c_i], v)
    doc.add_paragraph()


