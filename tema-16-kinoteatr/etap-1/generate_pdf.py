class TZPDF(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("DejaVu", "I", 8)
        self.set_text_color(100, 100, 100)
        self.cell(0, 6, "Тема 16. Кинотеатр — Этап 1 (пункты 1–3)", align="C")
        self.ln(8)
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-15)
        self.set_font("DejaVu", "I", 8)
        self.set_text_color(100, 100, 100)
        self.cell(0, 10, f"Страница {self.page_no()}/{{nb}}", align="C")
        self.set_text_color(0, 0, 0)


def reset_x(pdf):
    pdf.set_x(pdf.l_margin)


def h1(pdf, text):
    pdf.ln(3)
    reset_x(pdf)
    pdf.set_font("DejaVu", "B", 13)
    pdf.set_text_color(0, 112, 192)  # как голубые пункты в методичке
    pdf.multi_cell(0, 7, text)
    pdf.set_text_color(0, 0, 0)
    pdf.ln(1)


def h2(pdf, text):
    pdf.ln(2)
    reset_x(pdf)
    pdf.set_font("DejaVu", "B", 11)
    pdf.multi_cell(0, 6, text)
    pdf.ln(0.5)


def body(pdf, text):
    reset_x(pdf)
    pdf.set_font("DejaVu", "", 10)
    pdf.multi_cell(0, 5.5, text)
    pdf.ln(0.5)


def bold(pdf, text):
    reset_x(pdf)
    pdf.set_font("DejaVu", "B", 10)
    pdf.multi_cell(0, 5.5, text)


def bullet(pdf, text):
    pdf.set_font("DejaVu", "", 10)
    pdf.set_x(pdf.l_margin + 4)
    pdf.multi_cell(pdf.w - pdf.r_margin - pdf.l_margin - 4, 5.5, f"•  {text}")


def simple_table(pdf, headers, rows, col_widths):
    def draw_row(cells, bold_f=False, fill=False):
        pdf.set_font("DejaVu", "B" if bold_f else "", 7.5)
        line_h = 4.3
        heights = []
        for i, c in enumerate(cells):
            n = len(pdf.multi_cell(col_widths[i], line_h, c, dry_run=True, output="LINES"))
            heights.append(max(1, n) * line_h)
        row_h = max(heights)
        if pdf.get_y() + row_h > 285:
            pdf.add_page()
        x0 = pdf.l_margin
        y0 = pdf.get_y()
        for i, c in enumerate(cells):
            x = x0 + sum(col_widths[:i])
            if fill:
                pdf.set_fill_color(220, 235, 245)
                pdf.rect(x, y0, col_widths[i], row_h, style="DF")
            else:
                pdf.rect(x, y0, col_widths[i], row_h)
            pdf.set_xy(x + 0.5, y0 + 0.4)
            pdf.multi_cell(col_widths[i] - 1, line_h, c)
        pdf.set_y(y0 + row_h)

    draw_row(headers, bold_f=True, fill=True)
    for row in rows:
        draw_row(row)


